export const TOTAL_PREGNANCY_WEEKS = 40
const MS_PER_WEEK = 7 * 24 * 60 * 60 * 1000

export function eventDate(dueDate: Date, week: number): Date {
  return new Date(
    dueDate.getTime() - (TOTAL_PREGNANCY_WEEKS - week) * MS_PER_WEEK,
  )
}
